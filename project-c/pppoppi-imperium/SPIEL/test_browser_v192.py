from pathlib import Path
import hashlib, json,re
from playwright.sync_api import sync_playwright
P=Path(__file__).resolve().parent
OUT=P/'evidence_v192';OUT.mkdir(exist_ok=True)
html=(P/'index.html').read_text()
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(P/m.group(1)).read_text()+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(P/m.group(1)).read_text()+'</script>',html)
checks=[];shots=[];errors=[];requests=[]
def check(cond,title):
 checks.append({'title':title,'passed':bool(cond)})
 print(('PASS' if cond else 'FAIL'),title,flush=True)
 if not cond:raise AssertionError(title)
def snap(page,name):
 path=OUT/name;page.screenshot(path=str(path),animations='disabled')
 shots.append({'file':name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'bytes':path.stat().st_size})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=b.new_page(viewport={'width':1460,'height':870},accept_downloads=True)
 page.on('pageerror',lambda error:errors.append(str(error)))
 page.on('request',lambda req:requests.append(req.url) if req.url.startswith('http') else None)
 page.set_content(html,wait_until='load');page.set_default_timeout(7500)
 check(page.evaluate('PPStrategicAI?.version')=='1.9.2','Strategie-KI geladen')
 check(page.locator('#pp-ai-button').count()==1,'KI-Inspektor sichtbar')
 check(page.locator('#pp-ai-drawer').is_hidden(),'KI-Inspektor verdeckt keine Spielansicht')
 snap(page,'01_Buero_mit_Strategiebutton.png')
 page.evaluate("NeoEconomy.start('1-3')")
 check(page.evaluate('NeoEconomy.getState().companies.filter(x=>x.type===\'ai\').length')==3,'Drei KI-Konkurrenten erzeugt')
 page.evaluate("NeoEconomy.open('calendar')")
 page.locator('[data-econ="END_TURN"]').click()
 check(page.evaluate('NeoEconomy.getState().phase')=='REPORT','Computerzüge und Monatsabschluss vollständig')
 check(page.evaluate("NeoEconomy.getState().events.filter(e=>e.type==='KI_ENTSCHEIDUNG').length")>0,'KI-Entscheidungsprotokoll gespeichert')
 page.locator('#pp-ai-button').click()
 check(page.locator('#pp-ai-drawer').is_visible(),'KI-Protokoll bedienbar')
 check(page.locator('#pp-ai-drawer article').count()>0,'Strategiebegründungen werden angezeigt')
 check(any(('A'+str(n)) in page.locator('#pp-ai-drawer').inner_text() for n in (1,2,3)),'Entscheidungen sind Unternehmen zugeordnet')
 snap(page,'02_KI_Entscheidungsprotokoll.png')
 page.locator('#pp-ai-close').click()
 check(page.locator('#pp-ai-drawer').is_hidden(),'KI-Protokoll schließt ohne Spielaktion')
 page.evaluate("NeoEconomy.open('report')")
 snap(page,'03_Monatsabschluss_mit_KI.png')
 before=page.evaluate('JSON.stringify(NeoEconomy.getState())')
 page.locator('#pp-ai-button').click()
 page.locator('#pp-ai-close').click()
 check(page.evaluate('JSON.stringify(NeoEconomy.getState())')==before,'KI-Protokoll ist vollständig schreibgeschützt')
 page.locator('[data-econ="NEXT_MONTH"]').click()
 check(page.evaluate('NeoEconomy.getState().month')==2,'Nächster Monat erreichbar')
 page.locator('#closeBtn').click()
 with page.expect_download() as d:page.locator('#saveGame').click()
 payload=json.loads(Path(d.value.path()).read_text())
 check(payload['month']==2,'Spielstand mit KI-Historie exportiert')
 check(any(x['type']=='KI_ENTSCHEIDUNG' for x in payload['events']),'KI-Entscheidungen überleben Export')
 page.locator('#loadEconFile').set_input_files({'name':'ki-spielstand.json','mimeType':'application/json','buffer':json.dumps(payload,ensure_ascii=False).encode('utf8')})
 check(page.evaluate('NeoEconomy.getState().month')==2,'KI-Spielstand wieder eingelesen')
 check(page.evaluate('typeof PPNavigation191')=='object','Alte Navigation unverändert aktiv')
 mobile=b.new_page(viewport={'width':390,'height':800})
 mobile.set_content(html)
 mobile.locator('#pp-ai-button').click()
 check(mobile.locator('#pp-ai-drawer').is_visible(),'KI-Protokoll auf Mobilgerät öffnet')
 check(mobile.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'Keine horizontale Mobil-Überbreite')
 snap(mobile,'04_KI_Protokoll_mobil.png')
 check(not errors,'Keine JavaScript-Ausnahme im Browser')
 check(not requests,'Offline, keine HTTP-Anfragen')
 b.close()
result={'version':'1.9.2','passed':sum(x['passed'] for x in checks),'checks':checks,'screenshots':shots,'js_errors':errors,'http_requests':requests,'browser':'Chromium, eingebettete lokale Dateien','kubuntu_endtest':'zurueckgestellt','c64_test':'nicht ausgefuehrt'}
(OUT/'BROWSER_QA_V192.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
print('SUMME',result['passed'],'/',len(checks),'SCREENSHOTS',len(shots))
