from pathlib import Path
from playwright.sync_api import sync_playwright
import json, re, hashlib
ROOT=Path(__file__).resolve().parent
shots=ROOT/'screenshots_v16';shots.mkdir(exist_ok=True)
html=(ROOT/'index.html').read_text()
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(ROOT/m.group(1)).read_text()+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(ROOT/m.group(1)).read_text()+'</script>',html)
checks=[];errors=[];remote=[]
def ck(v,label):
 checks.append({'label':label,'passed':bool(v)})
 print('PASS' if v else 'FAIL',label,flush=True)
 assert v,label
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':930},accept_downloads=True)
 page.set_default_timeout(5500)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('request',lambda r:remote.append(r.url) if r.url.startswith('http') else None)
 page.set_content(html,wait_until='load')
 ck(page.evaluate('typeof NeoEconomy')=='object','V1.6-Oberfläche geladen')
 ck(page.evaluate('typeof PPProfi')=='object','Raffinerieadapter geladen')
 ck(page.evaluate('typeof PPSkillProfi')=='object','Erweitertes Geschicklichkeitsmodul geladen')
 page.screenshot(path=str(shots/'01_Buero_V16.png'),full_page=True)
 page.locator('#startGame').click();page.locator('[data-ui=newgame]').click()
 ck(page.evaluate('NeoEconomy.getState().refinery.version')=='pppoppi.refinery/1.0','Neue Partie mit Raffineriedaten')
 page.evaluate("NeoEconomy.open('claim')")
 page.locator('[data-econ=SURVEY]').click();page.locator('[data-econ=BUY]').click()
 page.evaluate("NeoEconomy.send('DRILL','BERLIN-1')");page.evaluate("NeoEconomy.send('PUMP','BERLIN-1')")
 ck(page.evaluate('NeoEconomy.getState().claims["BERLIN-1"].inventoryMilli')>=10000,'Rohöl im Feldlager')
 page.evaluate("NeoEconomy.open('factory')")
 ck(page.locator('[data-go=refinery]').count()>=1,'Raffinerie vom Industriehof erreichbar')
 page.locator('[data-go=refinery]').last.click()
 ck(page.locator('[data-econ=REFINERY_BUILD]').count()==1,'Raffineriebau verfügbar')
 page.screenshot(path=str(shots/'02_Raffinerie_vor_Bau.png'),full_page=True)
 page.locator('[data-econ=REFINERY_BUILD]').click()
 ck(page.evaluate('NeoEconomy.getState().refinery.plants.H1.BERLIN.built'),'Bau im echten Spielzustand')
 page.evaluate("NeoEconomy.open('refinery')")
 page.locator('[data-econ=REFINE_BATCH]').click()
 ck(page.evaluate('NeoEconomy.getState().refinery.plants.H1.BERLIN.productMilli')==9000,'Verarbeitung erzeugt genau 9 bbl Fertigware')
 page.evaluate("NeoEconomy.open('refinery')")
 page.screenshot(path=str(shots/'03_Raffinerie_Produktion.png'),full_page=True)
 page.locator('[data-econ=ROUTE_BUILD]').click()
 page.evaluate("NeoEconomy.open('refinery')")
 page.locator('[data-econ=REFINED_SELL]').click()
 ck(page.evaluate('NeoEconomy.getState().refinery.plants.H1.BERLIN.productMilli')==0,'Verkauf leert Fertigwarenbestand')
 ck(page.evaluate('NeoEconomy.getState().refinery.salesMilli.BERLIN')==9000,'Absatzbegrenzung zählt Verkäufe')
 page.evaluate("NeoEconomy.open('refinery')")
 page.screenshot(path=str(shots/'04_Raffinerie_Verkauf.png'),full_page=True)
 ck(page.evaluate('NeoEconomy.getState().refinery.story.length')==4,'Vier gespeicherte verknüpfte Figurenereignisse')
 page.evaluate("NeoEconomy.open('boardroom')")
 ck(page.locator('[data-go=chronicle]').count()==1,'Firmenchronik im Vorstand erreichbar')
 page.locator('[data-go=chronicle]').click()
 ck(page.locator('.econ-card').count()>=4,'Ereignisfolge sichtbar')
 page.screenshot(path=str(shots/'05_Figurenchronik.png'),full_page=True)
 page.locator('#closeBtn').click()
 with page.expect_download() as dl: page.locator('#saveGame').click()
 sav=ROOT/'test_export_v16.json';dl.value.save_as(str(sav))
 ck(json.loads(sav.read_text())['refinery']['plants']['H1']['BERLIN']['route'],'Spielstand exportiert Werk und Route')
 page.locator('#loadGame').click();page.locator('#loadEconFile').set_input_files(str(sav))
 page.wait_for_function('NeoEconomy.getState().refinery.salesMilli.BERLIN===9000')
 ck(page.evaluate('NeoEconomy.getState().refinery.salesMilli.BERLIN')==9000,'Spielstandimport bewahrt Absatz')
 # New skill profile with binding optional prep, under actual minigame.
 page.evaluate("NeoEconomy.start('1-2')")
 page.evaluate("NeoEconomy.open('claim')")
 page.locator('#econClaim').select_option('BRANDENBURG-1')
 page.locator('[data-econ=SURVEY]').click();page.locator('[data-econ=BUY]').click()
 page.evaluate("NeoEconomy.open('workshop')")
 page.locator('[data-econ=DRILL_SELF_START]').click()
 ck(page.locator('#skillMode').count()==1,'Schwierigkeitswahl im Bohrspiel')
 page.locator('#skillMode').select_option('profi')
 before=page.evaluate('NeoEconomy.getState().minigame.stage')
 page.locator('[data-arcade=drill-check]').click()
 ck(page.evaluate('NeoEconomy.getState().minigame.stage')==before,'Profischutz verlangt Vorbereitung ohne Fehlversuch')
 page.locator('[data-arcade=profi-prep]').click()
 ck(page.evaluate('PPSkillProfi.status().ready'),'Vorbereitung aktiv')
 page.screenshot(path=str(shots/'06_Bohrspiel_Profi.png'),full_page=True)
 # preserve state by export during open minigame by original game mechanics
 page.locator('#closeBtn').click()
 with page.expect_download() as dl: page.locator('#saveGame').click()
 sav2=ROOT/'test_mid_mini_v16.json';dl.value.save_as(str(sav2))
 ck(json.loads(sav2.read_text())['minigame']['kind']=='DRILL','Laufendes Minispiel exportierbar')
 mobile=browser.new_page(viewport={'width':390,'height':844})
 mobile.set_content(html,wait_until='load')
 mobile.locator('#startGame').click();mobile.locator('[data-ui=newgame]').click();mobile.evaluate("NeoEconomy.open('refinery')")
 ck(mobile.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Raffinerie ohne horizontales Scrollen auf Mobil')
 mobile.screenshot(path=str(shots/'07_Mobil_Raffinerie.png'),full_page=True)
 ck(not errors,'Keine ungefangenen JavaScript-Fehler')
 ck(not remote,'Keine externen Netzwerkanfragen')
 browser.close()
manifest={'browser':'Chromium via playwright, HTML/JS/CSS eingebettet, kein echter file:// Kubuntu-Test','checks':checks,'passed':sum(x['passed'] for x in checks),'total':len(checks),'screenshots':[{'file':f.name,'sha256':hashlib.sha256(f.read_bytes()).hexdigest()} for f in sorted(shots.glob('*.png'))], 'errors':errors,'network':remote}
(ROOT/'BROWSER_NACHWEIS_V16.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2))
print('RESULT',manifest['passed'], '/', manifest['total'])
