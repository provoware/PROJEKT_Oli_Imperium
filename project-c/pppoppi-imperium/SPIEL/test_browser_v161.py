from pathlib import Path
from playwright.sync_api import sync_playwright
import json,re,hashlib
ROOT=Path(__file__).resolve().parent
SHOTS=ROOT/'screenshots_v161';SHOTS.mkdir(exist_ok=True)
html=(ROOT/'index.html').read_text(encoding='utf-8')
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(ROOT/m.group(1)).read_text()+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(ROOT/m.group(1)).read_text()+'</script>',html)
errors=[];requests=[];assertions=[]
def check(c,m):
    assertions.append({'name':m,'passed':bool(c)})
    print(('PASS ' if c else 'FAIL ')+m,flush=True)
    if not c:raise AssertionError(m)
with sync_playwright() as play:
    browser=play.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':930},accept_downloads=True)
    page.set_default_timeout(6500)
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.on('request',lambda r: requests.append(r.url) if r.url.startswith('http') else None)
    page.set_content(html,wait_until='load')
    check(page.evaluate('typeof NeoEconomy')=='object','Echtes Büro geladen')
    check(page.evaluate('PPProfi.version')=='pppoppi.refinery/1.1','Verteilungsmodul 1.1 geladen')
    page.screenshot(path=str(SHOTS/'01_Buero_V161.png'),full_page=True)
    page.locator('#startGame').click()
    page.locator('[data-ui=newgame]').click()
    check(page.evaluate('NeoEconomy.getState().month')==1,'Neue Partie im tatsächlichen Browser gestartet')
    page.evaluate("NeoEconomy.open('claim')")
    for action in ['SURVEY','BUY','DRILL','PUMP']:
        page.locator(f'[data-econ={action}]').click()
    page.evaluate("NeoEconomy.open('refinery')")
    page.locator('[data-econ=REFINERY_BUILD]').click()
    page.evaluate("NeoEconomy.open('refinery')")
    page.locator('[data-econ=REFINE_BATCH]').click()
    page.evaluate("NeoEconomy.open('refinery')")
    page.locator('[data-econ=ROUTE_BUILD]').click()
    page.evaluate("NeoEconomy.open('refinery')")
    page.screenshot(path=str(SHOTS/'02_Raffinerie_Vor_Auftrag.png'),full_page=True)
    initial=page.evaluate('NeoEconomy.getState().companies[0].cashCent')
    page.locator('[data-econ=REFINED_SELL]').click()
    check(page.evaluate('NeoEconomy.getState().refinery.offers.length')==1,'Produktverkauf nur vorgemerkt')
    check(page.evaluate('NeoEconomy.getState().companies[0].cashCent')==initial,'Keine vorzeitige Auszahlung')
    page.evaluate("NeoEconomy.open('computer')")
    with page.expect_download() as download_info:
        page.locator('[data-ui=export]').click()
    download=download_info.value
    backup_file=ROOT/'qa_auftrag_v161.json'
    download.save_as(str(backup_file))
    check(json.loads(backup_file.read_text())['refinery']['offers'][0]['qtyMilli']==9000,'Offener Auftrag im JSON-Export gesichert')
    page.locator('#loadEconFile').set_input_files(str(backup_file))
    page.wait_for_function("document.getElementById('toast')?.textContent?.includes('Spielstand geprüft und übernommen')")
    check(page.evaluate('NeoEconomy.getState().refinery.offers[0].qtyMilli')==9000,'Gespeicherter Auftrag wieder importiert')
    page.evaluate("NeoEconomy.open('refinery')")
    check('verbindlich' in page.locator('#dialogContent').inner_text(),'Deutliche Kennzeichnung als Monatsauftrag')
    page.screenshot(path=str(SHOTS/'03_Monatsauftrag_Vorgemerkt.png'),full_page=True)
    page.evaluate("NeoEconomy.open('calendar')")
    page.locator('[data-econ=END_TURN]').click()
    check(page.evaluate('NeoEconomy.getState().phase') in ['REPORT','RESCUE'],'Monatsabschluss inklusive Computerzüge')
    check(page.evaluate('NeoEconomy.getState().refinery.offers.length')==0,'Aufträge nach der Abrechnung geleert')
    check(page.evaluate('NeoEconomy.getState().lastReport.refinery.regions.BERLIN.allocations.H1.soldMilli')==9000,'Angebot bei ausreichender Nachfrage voll verkauft')
    page.evaluate("NeoEconomy.open('report')")
    check('Raffinierter Produktmarkt' in page.locator('#dialogContent').inner_text(),'Abrechnungsanzeige erklärt Produktmarkt')
    page.screenshot(path=str(SHOTS/'04_Monatsabschluss_Markt.png'),full_page=True)
    # Inject a clearly marked synthetic test fixture through the real UI's engine.
    page.evaluate('''() => { const e=NeoEconomy.engine; const original=e.fresh; e.fresh=(opts)=>{let s=original({...opts,humans:2,ais:0}); for(let i=1;i<=2;i++){let id='H'+i,c=s.claims['BERLIN-'+i],p=s.refinery.plants[id].BERLIN;c.owner=id;c.drilled=true;p.built=true;p.route=true;p.productMilli=18000;}return s;}; }''')
    page.evaluate("NeoEconomy.start('2-0')")
    check(page.evaluate('NeoEconomy.getState().companies.length')==2,'Testfixture mit zwei echten menschlichen Firmen geladen')
    for id in ['H1','H2']:
        page.evaluate("NeoEconomy.open('refinery')")
        page.locator('[data-econ=REFINED_SELL]').click()
        page.evaluate("NeoEconomy.open('refinery')")
        page.locator('[data-econ=REFINED_SELL]').click()
        page.evaluate("NeoEconomy.open('calendar')")
        page.locator('[data-econ=END_TURN]').click()
        if id=='H1':
            check('Spielerwechsel' in page.locator('#dialogContent').inner_text() or page.evaluate('NeoEconomy.getState().companies[NeoEconomy.getState().turnIndex].id')=='H2','Verdeckte Spielerübergabe')
            page.screenshot(path=str(SHOTS/'05_Vertrauliche_Uebergabe.png'),full_page=True)
            page.locator('[data-ui=handoff-ok]').click()
    alloc=page.evaluate('NeoEconomy.getState().lastReport.refinery.regions.BERLIN.allocations')
    check(alloc['H1']['soldMilli']==13500 and alloc['H2']['soldMilli']==13500,'Wettbewerb 18 zu 18 ergibt 13,5 zu 13,5 Barrel')
    check(alloc['H1']['returnedMilli']==4500,'Restware geht zurück ins Firmenlager')
    page.evaluate("NeoEconomy.open('report')")
    page.screenshot(path=str(SHOTS/'06_Fairer_Mehrspielermarkt.png'),full_page=True)
    check(not errors,'Keine JavaScript-Laufzeitfehler')
    check(not requests,'Keine Netzwerkanfragen')
    browser.close()
manifest={'tests':assertions,'passed':sum(a['passed'] for a in assertions),'page_errors':errors,'network_requests':requests,'screenshots':{f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in SHOTS.glob('*.png')},'method':'Chromium echte Bedienung; gleiche Dateien mittels Einbettung offline geladen; bei den Mehrspielerbildern ausdrücklich synthetischer Startspielstand'}
(ROOT/'qa_browser_v161.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2))
print('FINAL',manifest['passed'],'tests',len(manifest['screenshots']),'screenshots')
