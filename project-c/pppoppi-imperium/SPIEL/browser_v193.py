from pathlib import Path
import json,re,hashlib
from playwright.sync_api import sync_playwright
P=Path(__file__).parent.resolve(); O=P/'evidence_v193';SH=O/'screenshots';SH.mkdir(exist_ok=True,parents=True)
html=(P/'index.html').read_text()
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(P/m.group(1)).read_text()+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(P/m.group(1)).read_text()+'</script>',html)
checks=[]; shots=[]; errs=[];network=[]
def check(v,t):
 checks.append({'check':t,'passed':bool(v)});print('PASS' if v else 'FAIL',t,flush=True)
 if not v:raise AssertionError(t)
def shot(page,name):
 file=SH/name;page.screenshot(path=str(file),animations='disabled')
 shots.append({'name':name,'sha256':hashlib.sha256(file.read_bytes()).hexdigest(),'bytes':file.stat().st_size})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=b.new_page(viewport={'width':1440,'height':860},accept_downloads=True)
 page.on('pageerror',lambda x:errs.append(str(x)))
 page.on('request',lambda r:network.append(r.url) if r.url.startswith('http') else None)
 page.set_content(html,wait_until='load');page.set_default_timeout(9000)
 check(page.evaluate('typeof PPLogisticsAI')=='object','Strategisches Logistikmodul geladen')
 check(page.evaluate('PPLogisticsAI.version')=='1.9.3','Logistikversion eindeutig')
 check(page.locator('#pp-ai-button').count()==1,'KI-Protokoll verfügbar')
 shot(page,'01_Buero_V193.png')
 page.evaluate("NeoEconomy.start('1-2')")
 check(page.evaluate("NeoEconomy.getState().companies.length")==3,'Partie mit zwei KI-Firmen startet')
 page.evaluate("NeoEconomy.open('calendar')")
 page.locator('[data-econ="END_TURN"]').click()
 check(page.evaluate("NeoEconomy.getState().phase")=='REPORT','Monatsabschluss erreichbar')
 page.locator('#pp-ai-button').click()
 check(page.locator('#pp-ai-drawer').is_visible(),'Entscheidungsfenster öffnet')
 page.locator('#pp-ai-close').click()
 check(page.locator('#pp-ai-drawer').is_hidden(),'Entscheidungsfenster schließt')
 page.locator('[data-econ="NEXT_MONTH"]').click()
 check(page.evaluate('NeoEconomy.getState().month')==2,'Folgemonat erreichbar')
 page.locator('#closeBtn').click()
 # Reproduzierbarer, künstlich vorbereiteter Spielstand mit echten Engine-Aktionen und Monatsabrechnung
 fixture=(O/'BELEGSPIELSTAND_V193.json').read_bytes()
 page.locator('#loadEconFile').set_input_files({'name':'V193-Beleg.json','mimeType':'application/json','buffer':fixture})
 page.wait_for_function("NeoEconomy.getState()?.phase==='REPORT'")
 check(page.evaluate("NeoEconomy.getState().phase")=='REPORT','Belegspielstand erfolgreich geladen')
 check(page.evaluate("NeoEconomy.getState().events.filter(x=>x.type==='KI_LOGISTIK').length")>=2,'Echte KI-Logistikhandlungen protokolliert')
 page.locator('#pp-ai-button').click()
 check('PUBLIC' in page.locator('#pp-ai-drawer').inner_text(),'Öffentlicher Transport im KI-Protokoll sichtbar')
 before=page.evaluate('JSON.stringify(NeoEconomy.getState())')
 shot(page,'02_KI_Logistikprotokoll.png')
 page.locator('#pp-ai-close').click()
 check(before==page.evaluate('JSON.stringify(NeoEconomy.getState())'),'Protokoll verändert keinen Spielzustand')
 page.evaluate("NeoEconomy.open('report')")
 shot(page,'03_Monatsbericht_Konkurrenz.png')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 check(page.locator('.public-flow').count()==1,'Öffentliche Netzübersicht angezeigt')
 shot(page,'04_Oeffentliches_Netz.png')
 page.locator('#closeBtn').click()
 with page.expect_download() as download:page.locator('#saveGame').click()
 saved=json.loads(Path(download.value.path()).read_text())
 check(saved['month']==1 and saved['phase']=='REPORT','Spielstand exportiert')
 check(saved['publicNetwork']['monthly'],'Netz-Monatsberichte im Export vorhanden')
 page.locator('#loadEconFile').set_input_files({'name':'Spielstand-V193.json','mimeType':'application/json','buffer':json.dumps(saved,ensure_ascii=False).encode()})
 page.wait_for_function('NeoEconomy.getState()?.month===1')
 check(page.evaluate('NeoEconomy.getState().month')==1,'Reimport erfolgreich')
 m=b.new_page(viewport={'width':390,'height':820})
 m.set_content(html)
 check(m.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'Mobile Breite ohne horizontalen Überlauf')
 m.locator('#pp-ai-button').click()
 check(m.locator('#pp-ai-drawer').is_visible(),'Mobiles KI-Protokoll nutzbar')
 shot(m,'05_Mobile_Ansicht.png')
 check(not errs,'Keine JavaScript-Laufzeitfehler')
 check(not network,'Keine HTTP-Netzwerkanfragen')
 b.close()
res={'version':'1.9.3','passed':sum(x['passed'] for x in checks),'total':len(checks),'checks':checks,'screenshots':shots,'errors':errs,'requests':network,'method':'Chromium, lokale Programmdateien eingebettet; kein direkter file://-Kubuntu-Test','referenceC64':'nicht geprüft'}
(O/'BROWSER_QA_V193.json').write_text(json.dumps(res,ensure_ascii=False,indent=2))
print('BROWSER: ',res['passed'],'/',res['total'],'screens',len(shots))
