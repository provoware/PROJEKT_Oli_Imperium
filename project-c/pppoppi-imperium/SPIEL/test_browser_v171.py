from pathlib import Path
import re, json, hashlib
from playwright.sync_api import sync_playwright
P=Path(__file__).resolve().parent
html=(P/'index.html').read_text()
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(P/m.group(1)).read_text()+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(P/m.group(1)).read_text()+'</script>',html)
OUT=P/'screenshots_v171';OUT.mkdir(exist_ok=True)
tests=[]; errors=[];requests=[];pics=[]
def check(x,name):
 assert x,name
 tests.append(name)
 print(f'PASS {len(tests):02} {name}',flush=True)
def picture(page,name):
 f=OUT/name
 page.screenshot(path=str(f),full_page=True,animations='disabled')
 pics.append({'file':name,'sha256':hashlib.sha256(f.read_bytes()).hexdigest(),'test':tests[-1] if tests else None})
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=b.new_page(viewport={'width':1480,'height':950},accept_downloads=True)
 page.set_default_timeout(8000)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.on('request',lambda e:requests.append(e.url) if e.url.startswith('http') else None)
 page.set_content(html,wait_until='load')
 check(page.evaluate('typeof NeoEconomy')=='object','Echte interaktive Büroansicht lädt im Chromium')
 check(page.evaluate("PPPublicNetwork.version==='pppoppi.publicnetwork/1.0'"),'Neue öffentliche Netzschicht im Browser geladen')
 picture(page,'01_Buero_Neo_Retro.png')
 page.locator('#startGame').click();page.locator('[data-ui=newgame]').click()
 check(page.evaluate('NeoEconomy.getState().month')==1,'Partie startet')
 # Fixtures: realistic mid-game factory/region logistics setup for screen behavior; do not alter prod code.
 page.evaluate('''() => {let orig=NeoEconomy.engine.fresh;NeoEconomy.engine.fresh=function(o){let s=orig({...o,humans:2,ais:0});for(const f of s.companies)for(const r of NeoEconomy.engine.REGIONS){s.refinery.plants[f.id][r.id].built=true;s.refinery.plants[f.id][r.id].route=true;s.transport.firms[f.id][r.id].enabled=true;s.transport.firms[f.id][r.id].marketMilli=30000;}NeoEconomy.engine.validate(s);return s;};}''')
 page.evaluate("NeoEconomy.start('2-0')")
 page.evaluate("NeoEconomy.open('transport')")
 check(page.locator('[data-go=publicNetwork]').count()>0,'Regionale Leitstelle führt ins öffentliche Netz')
 page.locator('[data-go=publicNetwork]').first.click()
 check('ÖFFENTLICHE VERKEHRSZENTRALE' in page.locator('#dialogContent').inner_text(),'Öffentliche Leitstelle ist erreichbar')
 check(page.locator('.public-flow').count()==1,'Netzdiagramm Berlin-Brandenburg-Nord wird angezeigt')
 picture(page,'02_Oeffentliches_Netz_Uebersicht.png')
 page.locator('[data-econ=PUBLIC_CONNECT][data-from=BERLIN][data-to=BRANDENBURG]').click()
 check('BERLIN>BRANDENBURG' in page.evaluate("NeoEconomy.getState().publicNetwork.connections.H1"),'H1 bezahlt Anschluss Berlin-Brandenburg')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 picture(page,'03_Anschluss_gebaut.png')
 page.locator('[data-econ=PUBLIC_QUEUE][data-to=BRANDENBURG]').click()
 check(page.evaluate('NeoEconomy.getState().publicNetwork.queued.length')==1,'H1 sichert 9 Barrel für öffentliche Lieferung')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 picture(page,'04_Transportauftrag_vorgemerkt.png')
 # Set up a second valid transport order for H1 to stress 24 bbl shared capacity.
 page.locator('[data-econ=PUBLIC_QUEUE][data-to=BRANDENBURG]').click()
 check(page.evaluate('NeoEconomy.getState().publicNetwork.queued.length')==2,'Zweiter Auftrag ohne Vorab-Kapazität')
 page.evaluate("NeoEconomy.open('calendar')")
 page.locator('[data-econ=END_TURN]').click()
 check(page.evaluate('NeoEconomy.getState().turnIndex')==1,'Vertraulicher Wechsel zu H2 ausgelöst')
 page.locator('[data-ui=handoff-ok]').click()
 page.evaluate("NeoEconomy.open('publicNetwork')")
 picture(page,'05_Zweiter_Spieler.png')
 page.locator('[data-econ=PUBLIC_CONNECT][data-to=BRANDENBURG]').click()
 page.evaluate("NeoEconomy.open('publicNetwork')")
 page.locator('[data-econ=PUBLIC_QUEUE][data-to=BRANDENBURG]').click()
 check(page.evaluate('NeoEconomy.getState().publicNetwork.queued.length')==3,'Zweite Firma tritt um dieselbe Kapazität an')
 page.evaluate("NeoEconomy.open('calendar')")
 page.locator('[data-econ=END_TURN]').click()
 check(page.evaluate('NeoEconomy.getState().phase')=='REPORT','Monatsende: öffentliche Zuteilung berechnet')
 r=page.evaluate('NeoEconomy.getState().lastReport.publicNetwork')
 check(sum(o['acceptedMilli'] for o in r['freight'])<=24000,'Kein doppelter Verbrauch der öffentlichen 24-bbl-Strecke')
 check(sum(o['requestedMilli'] for o in r['freight'])==27000,'27 Barrel Gesamtnachfrage korrekt erfasst')
 check(r['capacity']['B-BB']['usedMilli']==24000,'Genau 24 Barrel fair verteilt')
 picture(page,'06_Faire_Zuteilung_Abschluss.png')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 check('Letzter Netzausgleich' in page.locator('#dialogContent').inner_text(),'Letzter Monatsausgleich sichtbar')
 check('Zugewiesen' in page.locator('#dialogContent').inner_text(),'Fairer Monatsabschluss firmengenau angezeigt')
 picture(page,'07_Zuteilung_im_Netz.png')
 page.evaluate("document.querySelector('#dialog').scrollTop=document.querySelector('#dialog').scrollHeight")
 picture(page,'07b_Zuteilung_Detail.png')
 page.evaluate("NeoEconomy.open('report')")
 page.locator('[data-econ=NEXT_MONTH]').click()
 check(page.evaluate('NeoEconomy.getState().month')==2,'Folgende Spielmonat beginnt')
 check(page.evaluate('NeoEconomy.getState().publicNetwork.received.H1.BRANDENBURG')>0,'Waren in Brandenburg nach Monatswechsel angekommen')
 # Export / Import actual file payload through downloaded browser file
 page.locator('#closeBtn').click()
 with page.expect_download() as info: page.locator('#saveGame').click()
 payload=json.loads(Path(info.value.path()).read_text())
 check(payload['publicNetwork']['version']=='pppoppi.publicnetwork/1.0','Export enthält Verkehr, offene Lieferungen und Handelslager')
 check(page.evaluate("PPPublicNetwork.validate(NeoEconomy.getState())") is True,'Geladene Netzstruktur schemaprüfbar')
 page.locator('#loadEconFile').set_input_files({'name':'abnahmestand.json','mimeType':'application/json','buffer':json.dumps(payload,ensure_ascii=False).encode('utf-8')})
 page.wait_for_function("document.querySelector('#toast')?.textContent?.includes('Spielstand geprüft und übernommen')")
 check(page.evaluate('NeoEconomy.getState().publicNetwork.received.H1.BRANDENBURG')==payload['publicNetwork']['received']['H1']['BRANDENBURG'],'Spielstand einschließlich öffentlicher Lieferungen tatsächlich importiert')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 picture(page,'08_Angelieferte_Ware.png')
 page.locator('[data-econ=PUBLIC_OFFER][data-to=BRANDENBURG]').click()
 check(page.evaluate('NeoEconomy.getState().publicNetwork.offers.length')==1,'Angelieferte Ware für den Exportmarkt vorgemerkt')
 check(page.evaluate('NeoEconomy.getState().publicNetwork.received.H1.BRANDENBURG')==payload['publicNetwork']['received']['H1']['BRANDENBURG']-9000,'Marktmenge aus Zielbestand korrekt reserviert')
 page.evaluate("NeoEconomy.open('publicNetwork')")
 page.evaluate("document.querySelector('#dialog').scrollTop=document.querySelector('#dialog').scrollHeight")
 picture(page,'08b_Exportangebot.png')
 mobile=b.new_page(viewport={'width':390,'height':844})
 mobile.on('pageerror',lambda e:errors.append('Mobil: '+str(e)))
 mobile.set_content(html)
 mobile.locator('#startGame').click();mobile.locator('[data-ui=newgame]').click()
 mobile.evaluate("NeoEconomy.open('publicNetwork')")
 check(mobile.locator('.public-flow').count()==1,'Öffentliches Netz auf kleinem Display aufrufbar')
 check(mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1'),'Keine horizontale Überbreite der Mobilansicht')
 picture(mobile,'09_Mobilansicht_Oeffentliches_Netz.png')
 check(not errors,'Keine JavaScript-Laufzeitfehler')
 check(not requests,'Offline: Keine Netzwerkanfrage')
 b.close()
result={'result':'passed','checks':len(tests),'screenshots':pics,'page_errors':errors,'requests':requests,'notes':'Browser per eingebetteten HTML/CSS/JS getestet. Direkter Kubuntu-Dateistart nicht geprüft.'}
(P/'evidence'/'qa_v171_browser.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
print('RESULT',len(tests),'Prüfungen',len(pics),'Screenshots')
