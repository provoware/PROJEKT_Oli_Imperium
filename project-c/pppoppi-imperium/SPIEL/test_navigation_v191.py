from pathlib import Path
from playwright.sync_api import sync_playwright
import json,re,hashlib,sys,traceback
ROOT=Path(__file__).resolve().parent
EVID=ROOT/'evidence_v191';EVID.mkdir(exist_ok=True)
src=(ROOT/'index.html').read_text(encoding='utf8')
src=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+(ROOT/m.group(1)).read_text(encoding='utf8')+'</style>',src)
src=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(ROOT/m.group(1)).read_text(encoding='utf8')+'</script>',src)
checks=[];shots=[];errors=[];requests=[];screens=[]
def verify(ok,name):
    checks.append({'name':name,'passed':bool(ok)});print(('PASS' if ok else 'FAIL'),name,flush=True)
    if not ok:raise AssertionError(name)
def snap(page,name):
    p=EVID/name;page.screenshot(path=str(p),animations='disabled',full_page=False)
    shots.append({'name':name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'size':p.stat().st_size})
with sync_playwright() as pw:
    b=pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=b.new_page(viewport={'width':1440,'height':900},accept_downloads=True)
    page.set_default_timeout(6500)
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.on('request',lambda req:requests.append(req.url) if req.url.startswith('http') else None)
    page.set_content(src,wait_until='load')
    verify(page.evaluate('typeof PPNavigation191')=='object','V1.9.1-Navigation geladen')
    verify(page.locator('.hotspot').count()==14,'Büro-Hotspots intakt')
    page.evaluate("PPNavigation191.open('map')")
    verify(page.evaluate("PPNavigation191.current()")=='startup','Fachseite ohne Partie führt sicher zum Spielstart')
    page.locator('[data-ui="newgame"]').click()
    verify(page.evaluate("PPNavigation191.current()")=='computer','Neue Partie öffnet Computer')
    verify(page.locator('#v191-navigator').count()==1,'Gemeinsame Navigation sichtbar')
    verify(page.evaluate('PPNavigation191.getTrail().length')==0,'Neue Partie hat keinen irreführenden Rückweg')
    snap(page,'01_Computer_mit_Navigation.png')
    page.locator('[data-go="map"]').first.click()
    verify(page.evaluate("PPNavigation191.current()")=='map','Bürocomputer erreicht Regionskarte')
    page.locator('[data-ui="region"]').first.click()
    verify(page.evaluate("PPNavigation191.current()")=='region','Karte erreicht Region')
    page.locator('[data-claim]').first.click()
    verify(page.evaluate("PPNavigation191.current()")=='claim','Region erreicht einzelnes Feld')
    snap(page,'02_Claim_mit_Rueckweg.png')
    st_before=page.evaluate('JSON.stringify(NeoEconomy.getState())')
    page.locator('#v191-navigator [data-nav="back"]').click()
    verify(page.evaluate("PPNavigation191.current()")=='region','Zurück führt von Claim zur Region')
    page.keyboard.press('Alt+ArrowLeft')
    verify(page.evaluate("PPNavigation191.current()")=='map','Alt+Pfeil links führt von Region zur Karte')
    verify(page.evaluate('JSON.stringify(NeoEconomy.getState())')==st_before,'Navigation verändert weder Öl, Zeit noch Geld')
    verify(page.locator('#v191-navigator').count()==1,'Navigation wird nicht mehrfach eingebaut')
    page.evaluate("PPNavigation191.open('unbekannt-v191')")
    verify(page.evaluate("PPNavigation191.current()")=='help','Ungültiger Bildschirm fällt auf Hilfe zurück')
    page.locator('#v191-navigator [data-nav="quick"]').click()
    verify(page.evaluate("PPNavigation191.current()")=='quick','Alle Bereiche über Übersicht erreichbar')
    snap(page,'03_Spielbereiche_Uebersicht.png')
    all_scenes=page.evaluate('PPNavigation191.getScenes()')
    verify(len(all_scenes)>=35,'Umfang des Szenenregisters ist vollständig')
    for name in all_scenes:
        before=len(errors)
        result=page.evaluate('(id)=>{PPNavigation191.open(id);return {scene:PPNavigation191.current(),title:document.getElementById("dialogTitle").textContent,content:document.getElementById("dialogContent").textContent.length,toolbar:document.querySelectorAll("#v191-navigator").length}}',name)
        screens.append({'requested':name,**result,'new_errors':errors[before:]})
    broken=[s for s in screens if s['new_errors'] or not s['content'] or s['toolbar']!=1]
    verify(not broken,f'Alle {len(all_scenes)} registrierten Ansichten rendern ohne JavaScript-Ausnahme')
    # Property exposed by bridge: true until handoff explicitly acknowledged.
    page.evaluate("PPNavigation191.open('calendar')")
    if page.locator('[data-econ="END_TURN"]').count():
        page.locator('[data-econ="END_TURN"]').click()
        current_phase=page.evaluate('NeoEconomy.getState().phase')
        if page.evaluate('NeoEconomy.needsHandoff()'):
            page.evaluate("PPNavigation191.open('finance')")
            verify(page.evaluate("PPNavigation191.current()")=='handoff','Vertrauliche Daten vor Spielerwechsel abgeschirmt')
            verify(page.locator('button[data-ui="handoff-ok"]').count()==1,'Einziger freigebender Wechselknopf bleibt sichtbar')
            verify(page.locator('#v191-navigator [data-nav="quick"]').is_disabled(),'Schnellübersicht während Übergabe gesperrt')
            snap(page,'04_Vertraulicher_Wechsel.png')
            page.locator('[data-ui="handoff-ok"]').click()
            verify(not page.evaluate('NeoEconomy.needsHandoff()'),'Übergabe erst durch bestätigende Eingabe frei')
        elif current_phase=='REPORT':
            page.evaluate("PPNavigation191.open('map')")
            verify(page.evaluate("PPNavigation191.current()")=='map' and page.evaluate('NeoEconomy.getState().phase')=='REPORT','Berichtsphase bleibt bei reinem Bildschirmwechsel bestehen')
            snap(page,'04_Monatsbericht_Sperre.png')
    # Dedicated two-human confidentiality proof without changing the normal test scenario.
    private=b.new_page(viewport={'width':1280,'height':800},accept_downloads=True)
    private.set_content(src,wait_until='load')
    private.evaluate("NeoEconomy.start('2-0')")
    private.evaluate("NeoEconomy.open('calendar')")
    private.locator('[data-econ="END_TURN"]').click()
    verify(private.evaluate('NeoEconomy.needsHandoff()'),'Zwei Menschen: vertrauliche Zugübergabe beginnt')
    private.evaluate("PPNavigation191.open('finance')")
    verify(private.evaluate("PPNavigation191.current()")=='handoff','Finanzbildschirm während Zugübergabe blockiert')
    verify(private.locator('#v191-navigator [data-nav="quick"]').is_disabled(),'Schnellübersicht bei Übergabe blockiert')
    private.locator('#closeBtn').click()
    private.locator('#saveGame').click()
    verify(not private.locator('#dialog').evaluate('(d)=>d.open'),'Speicherexport während Übergabe abgewiesen')
    private.evaluate("PPNavigation191.open('computer')")
    verify(private.evaluate("PPNavigation191.current()")=='handoff','Vertraulicher Wechsel auch nach Fensterschließen geschützt')
    snap(private,'06_Vertraulicher_Spielerwechsel.png')
    private.locator('[data-ui="handoff-ok"]').click()
    verify(not private.evaluate('NeoEconomy.needsHandoff()'),'Erst Bestätigung zeigt die nächste Firma')
    verify(private.evaluate("PPNavigation191.current()")=='computer','Nach Übergabe öffnet neuer Firmencomputer')
    private.close()
    # Sanierungsansicht mit ausdrücklich konstruierter und gültiger Spielstandprobe.
    rescue=b.new_page(viewport={'width':1280,'height':800})
    rescue.set_content(src,wait_until='load')
    state_text=rescue.evaluate("""() => {const E=NeoEconomy.engine;const s=E.fresh({humans:1,ais:1});s.phase='RESCUE';s.rescueIds=['H1'];s.companies[0].obligations.push({id:'TEST-SANIERUNG',priority:1,dueCent:1200000,paidCent:0,kind:'TEST'});E.validate(s);return JSON.stringify(s)}""")
    rescue.locator('#loadEconFile').set_input_files({'name':'rescue_test.json','mimeType':'application/json','buffer':state_text.encode()})
    verify(rescue.evaluate("NeoEconomy.getState()?.phase")=='RESCUE','Gültiger Rettungs-Spielstand wird geladen')
    verify(rescue.evaluate("PPNavigation191.current()")=='rescue','Sanierungsbildschirm bei Rettungsfall erreichbar')
    verify(rescue.locator('[data-econ="RESCUE_LOAN"]').count()==1,'Rettungskredit als echte Spielaktion verfügbar')
    rescue.close()
    page.locator('#v191-navigator [data-nav="desk"]').click()
    verify(not page.locator('#dialog').evaluate('(d)=>d.open'),'Büro-Schaltfläche schließt das Fenster')
    verify(not requests,'Keine externen Netzwerkanfragen')
    verify(not errors,'Keine unaufgefangenen Browserfehler')
    mob=b.new_page(viewport={'width':390,'height':800});mob.set_content(src,wait_until='load');mob.evaluate("PPNavigation191.open('startup')");mob.screenshot(path=str(EVID/'05_Mobilnavigation.png'))
    shots.append({'name':'05_Mobilnavigation.png','sha256':hashlib.sha256((EVID/'05_Mobilnavigation.png').read_bytes()).hexdigest(),'size':(EVID/'05_Mobilnavigation.png').stat().st_size})
    verify(mob.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobilansicht ohne horizontales Scrollen')
    b.close()
result={'version':'1.9.1','passed':sum(x['passed'] for x in checks),'checks':checks,'scenes':screens,'images':shots,'errors':errors,'requests':requests,'browser':'Chromium headless (embedded offline HTML, CSS, JavaScript)','kubuntu_end_test':'deferred','c64_emulator_test':'not_performed'}
(EVID/'QA_V191.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
print('SUMME',result['passed'],'/',len(checks),'SCENES',len(screens),'SCREENSHOTS',len(shots),flush=True)
