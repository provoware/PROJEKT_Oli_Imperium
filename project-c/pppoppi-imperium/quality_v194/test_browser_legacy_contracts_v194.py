#!/usr/bin/env python3
"""Legacy V0.8 contracts: natural fulfilment/breach, safe migration and journals.

All scenarios are generated by the historical V0.8 engine, not by editing
contract status, cash or accounting entries. Uses an isolated offline build.
"""
import json
import subprocess
import tempfile
from pathlib import Path

from playwright.sync_api import sync_playwright
from test_browser_legacy_special_v194 import export_state
from test_browser_natural_rescue_v194 import state
from test_browser_reimport_v194 import import_file

HERE = Path(__file__).resolve().parent


def check(label, condition):
    print(("PASS: " if condition else "FAIL: ") + label, flush=True)
    if not condition:
        raise AssertionError(label)


def main():
    with tempfile.TemporaryDirectory(prefix="pppoppi-legacy-contracts-") as temp:
        preview = Path(temp) / "preview"
        subprocess.run(
            ["node", str(HERE / "build.cjs"), str(preview)],
            check=True, timeout=90, capture_output=True, text=True,
        )
        check("Isolierter Offline-Aufbau", (preview / "index.html").is_file())
        errors, external = [], []
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch(headless=True)
            try:
                context = browser.new_context(
                    viewport={"width": 800, "height": 600},
                    accept_downloads=True, reduced_motion="reduce",
                )
                page = context.new_page()
                page.set_default_timeout(15000)
                page.on("pageerror", lambda error: errors.append(str(error)))
                page.on(
                    "request",
                    lambda request: external.append(request.url)
                    if request.url.startswith(("http://", "https://")) else None,
                )
                page.goto((preview / "index.html").as_uri(), wait_until="load")
                page.wait_for_function(
                    "typeof OliV08 === 'object' && typeof NeoEconomy === 'object'"
                )

                scenarios = page.evaluate("""() => {
                    const results = {};
                    for (const mode of ['DONE', 'BREACH']) {
                        let s = OliV08.fresh({
                            humans: 1, ais: 1, seed: 'LEGACY-CONTRACT-' + mode
                        });
                        let n = 0;
                        const run = type => {
                            s = OliV08.transition(s, {
                                type, companyId: 'H1', region: 'BERLIN',
                                requestId: 'contract-' + mode + '-' + (++n)
                            }).state;
                            OliV08.validate(s);
                        };
                        const actions = mode === 'DONE'
                            ? ['SURVEY', 'BUY', 'DRILL', 'PUMP', 'SIGN']
                            : ['SURVEY', 'BUY', 'SIGN'];
                        for (const type of actions) run(type);
                        run('END_TURN');
                        run('NEXT_MONTH');
                        const open = JSON.parse(JSON.stringify(s));
                        run('END_TURN');
                        const settled = JSON.parse(JSON.stringify(s));
                        run('NEXT_MONTH');
                        results[mode] = {open, settled, closed: s};
                    }
                    return results;
                }""")

                for mode in ("DONE", "BREACH"):
                    old = scenarios[mode]
                    open_save, settled, closed = (
                        old["open"], old["settled"], old["closed"]
                    )
                    old_firm = closed["companies"][0]
                    contract = old_firm["contracts"][0]
                    check(mode + ": regulär abgeschlossener V0.8-Vertrag",
                          open_save["schema"] == "pppoppi.berlin.save/0.8"
                          and open_save["month"] == 2
                          and open_save["phase"] == "TURN"
                          and open_save["companies"][0]["contracts"][0]["status"] == "OPEN"
                          and settled["companies"][0]["contracts"][0]["status"] == mode
                          and closed["month"] == 3 and closed["phase"] == "TURN")
                    check(mode + ": Lieferung und Vertragsstrafe plausibel",
                          (contract["soldMilli"] == contract["qtyMilli"]
                           if mode == "DONE" else contract["soldMilli"] == 0)
                          and (not any(o["kind"] == "VERTRAGSSTRAFE"
                                       for o in old_firm["obligations"])
                               if mode == "DONE" else
                               any(o["kind"] == "VERTRAGSSTRAFE"
                                   for o in old_firm["obligations"])))
                    before = state(page)
                    import_file(page, "contract-open-" + mode + ".json",
                                open_save, False)
                    check(mode + ": offener Altvertrag abgewiesen, Stand erhalten",
                          state(page) == before)

                    import_file(page, "contract-closed-" + mode + ".json",
                                closed, True)
                    migrated = state(page)
                    new_firm = migrated["companies"][0]
                    check(mode + ": Migration nach regulärer Abrechnung",
                          migrated["schema"] == "pppoppi.berlin.save/0.8.2"
                          and migrated["lineage"]["source"] == closed["schema"]
                          and migrated["month"] == closed["month"]
                          and migrated["phase"] == closed["phase"])
                    check(mode + ": Vertrag, Journal, Forderungen unverändert",
                          new_firm["contracts"] == old_firm["contracts"]
                          and new_firm["ledger"] == old_firm["ledger"]
                          and new_firm["obligations"] == old_firm["obligations"]
                          and new_firm["cashCent"] == old_firm["cashCent"]
                          and new_firm["debtCent"] == old_firm["debtCent"]
                          and new_firm["stats"] == old_firm["stats"])
                    check(mode + ": Historie und Doppelbuchungsschutz erhalten",
                          migrated["reports"] == closed["reports"]
                          and migrated["events"] == closed["events"]
                          and migrated["processedIds"] == closed["processedIds"]
                          and migrated["sequence"] == closed["sequence"])
                    check(mode + ": Eigentum und Restlager erhalten",
                          migrated["claims"]["BERLIN-1"]["owner"] == "H1"
                          and migrated["claims"]["BERLIN-1"]["inventoryMilli"]
                          == old_firm["fields"]["BERLIN"]["inventoryMilli"])
                    check(mode + ": exportierbar und technisch valide",
                          page.evaluate(
                              "NeoEconomy.engine.validate(NeoEconomy.getState())"
                          ) is True and export_state(page) == migrated)
                    import_file(page, "contract-repeat-" + mode + ".json",
                                migrated, True)
                    check(mode + ": erneuter Import ohne Doppelbuchung",
                          state(page) == migrated and export_state(page) == migrated)

                check("800x600 ohne horizontalen Ueberlauf",
                      page.evaluate(
                          "document.documentElement.scrollWidth <= innerWidth + 2"
                      ))
                check("Keine externen HTTP-Anfragen", not external)
                check("Keine JavaScript-Laufzeitfehler", not errors)
                print("ALTVERTRAGS-REGRESSION:", json.dumps({
                    "natural_outcomes": ["DONE", "BREACH"],
                    "rejected_open_contracts": 2,
                    "preserved": ["contracts", "ledger", "obligations",
                                  "cash", "debt", "reports", "events",
                                  "processedIds", "inventory"],
                    "release_gate": "BLOCKED",
                }, ensure_ascii=False), flush=True)
                context.close()
            finally:
                browser.close()


if __name__ == "__main__":
    main()
